import enum
from sqlalchemy import Column, String, Text, ForeignKey, Float, Integer, DateTime, Boolean, CheckConstraint
from sqlalchemy.orm import relationship
from app.database.base import Base
from app.models.base import UUIDMixin, TimestampMixin


class DecisionStatus(str, enum.Enum):
    """Lifecycle status for a recorded decision."""
    ACTIVE = "ACTIVE"
    SUPERSEDED = "SUPERSEDED"
    REVOKED = "REVOKED"


class ActionItemStatus(str, enum.Enum):
    """Lifecycle status for an action item."""
    PENDING = "PENDING"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"


class RiskSeverity(str, enum.Enum):
    """Severity ratings for identified meeting risks."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class QuestionStatus(str, enum.Enum):
    """Status of unresolved questions raised during a meeting."""
    OPEN = "OPEN"
    RESOLVED = "RESOLVED"
    DEFERRED = "DEFERRED"


class MeetingSummary(UUIDMixin, TimestampMixin, Base):
    """AI-generated executive and detailed summary of a meeting."""
    __tablename__ = "meeting_summaries"

    meeting_id = Column(
        String(36),
        ForeignKey("meetings.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    transcript_id = Column(
        String(36),
        ForeignKey("transcripts.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    executive_summary = Column(Text, nullable=False)
    detailed_summary = Column(Text, nullable=True)
    key_takeaways = Column(Text, nullable=True)  # Structured JSON string or markdown
    version = Column(Integer, default=1, nullable=False)
    provider_used = Column(String(50), nullable=True)  # e.g., 'ollama', 'deterministic'
    is_heuristic = Column(Boolean, nullable=True)  # True if generated by rule-based heuristic fallback
    fallback_warning = Column(Text, nullable=True)  # Safe transparency warning if fallback was invoked

    # Relationships
    meeting = relationship("Meeting", back_populates="summaries")
    transcript = relationship("Transcript", back_populates="summaries")


class Topic(UUIDMixin, TimestampMixin, Base):
    """Key topic or agenda item discussed during a meeting."""
    __tablename__ = "topics"

    meeting_id = Column(
        String(36),
        ForeignKey("meetings.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    title = Column(String(255), nullable=False)
    description = Column(Text, nullable=True)
    start_time = Column(Float, nullable=True)  # Discussion start time in seconds
    end_time = Column(Float, nullable=True)    # Discussion end time in seconds

    # Relationships
    meeting = relationship("Meeting", back_populates="topics")


class Decision(UUIDMixin, TimestampMixin, Base):
    """Explicit decision made during a meeting with evidence grounding and lifecycle tracking."""
    __tablename__ = "decisions"
    __table_args__ = (
        CheckConstraint(
            "supersedes_decision_id IS NULL OR supersedes_decision_id != id",
            name="ck_decisions_no_self_supersede"
        ),
    )

    meeting_id = Column(
        String(36),
        ForeignKey("meetings.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    description = Column(Text, nullable=False)
    rationale_or_context = Column(Text, nullable=True)
    decided_by = Column(String(255), nullable=True)
    evidence_segment_id = Column(
        String(36),
        ForeignKey("transcript_segments.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    timestamp_seconds = Column(Float, nullable=True)
    status = Column(
        String(50),
        default=DecisionStatus.ACTIVE.value,
        nullable=False,
        server_default=DecisionStatus.ACTIVE.value,
        index=True
    )
    supersedes_decision_id = Column(
        String(36),
        ForeignKey("decisions.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )

    # Relationships
    meeting = relationship("Meeting", back_populates="decisions")
    evidence_segment = relationship("TranscriptSegment", back_populates="decisions")
    superseded_decision = relationship(
        "Decision",
        remote_side="Decision.id",
        foreign_keys=[supersedes_decision_id],
        backref="superseding_decisions",
    )


class ActionItem(UUIDMixin, TimestampMixin, Base):
    """Committed task with assigned owner, deadline, and cross-meeting tracking."""
    __tablename__ = "action_items"

    meeting_id = Column(
        String(36),
        ForeignKey("meetings.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    description = Column(Text, nullable=False)
    owner_name = Column(String(255), nullable=True)
    owner_user_id = Column(
        String(36),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    deadline = Column(DateTime(timezone=True), nullable=True)
    status = Column(
        String(50),
        default=ActionItemStatus.PENDING.value,
        nullable=False,
        index=True
    )
    evidence_segment_id = Column(
        String(36),
        ForeignKey("transcript_segments.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    timestamp_seconds = Column(Float, nullable=True)

    # Commitment continuity across subsequent meetings
    last_reviewed_meeting_id = Column(
        String(36),
        ForeignKey("meetings.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    last_evidence_segment_id = Column(
        String(36),
        ForeignKey("transcript_segments.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    last_reviewed_at = Column(DateTime(timezone=True), nullable=True)

    # Relationships
    meeting = relationship("Meeting", foreign_keys=[meeting_id], back_populates="action_items")
    owner_user = relationship("User", back_populates="action_items")
    evidence_segment = relationship("TranscriptSegment", foreign_keys=[evidence_segment_id], back_populates="action_items")
    last_reviewed_meeting = relationship("Meeting", foreign_keys=[last_reviewed_meeting_id])
    last_evidence_segment = relationship("TranscriptSegment", foreign_keys=[last_evidence_segment_id])
    reviews = relationship(
        "ActionItemReview",
        back_populates="action_item",
        cascade="all, delete-orphan",
        order_by="ActionItemReview.reviewed_at.asc()",
    )


class ActionItemReview(UUIDMixin, TimestampMixin, Base):
    """Immutable audit entry recording a cross-meeting review of a committed action item."""
    __tablename__ = "action_item_reviews"

    action_item_id = Column(
        String(36),
        ForeignKey("action_items.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    meeting_id = Column(
        String(36),
        ForeignKey("meetings.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    evidence_segment_id = Column(
        String(36),
        ForeignKey("transcript_segments.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    reviewer_user_id = Column(
        String(36),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    status_at_review = Column(String(50), nullable=True)
    review_notes = Column(Text, nullable=True)
    reviewed_at = Column(DateTime(timezone=True), nullable=False)

    # Relationships
    action_item = relationship("ActionItem", back_populates="reviews")
    meeting = relationship("Meeting")
    evidence_segment = relationship("TranscriptSegment")
    reviewer_user = relationship("User")


